def text(value, name='muted', wrap=False):
    control = QLabel(value)
    control.setObjectName(name)
    control.setWordWrap(wrap)
    control.setTextFormat(Qt.PlainText)
    return control


def action(value, callback, name=None):
    control = QPushButton(value)
    control.setCursor(Qt.PointingHandCursor)
    if name:
        control.setObjectName(name)
    control.clicked.connect(callback)
    return control


class ElidedLabel(QLabel):
    """Keep long text from forcing the workspace wider than the screen."""
    def __init__(self, value, name='fileName'):
        super().__init__()
        self.full_text = value
        self.setObjectName(name)
        self.setMinimumWidth(0)
        self.setSizePolicy(QSizePolicy.Ignored, QSizePolicy.Preferred)
        self.setTextFormat(Qt.PlainText)
        self.setText(value)

    def setText(self, value):
        self.full_text = value
        self.setToolTip(value)
        super().setText(self.fontMetrics().elidedText(value, Qt.ElideMiddle, max(40, self.width())))

    def resizeEvent(self, event):
        super().resizeEvent(event)
        self.setText(self.full_text)


class OptionalLabel(QLabel):
    """Status details occupy space only when the worker supplies content."""
    def __init__(self, name):
        super().__init__()
        self.setObjectName(name)
        self.setTextFormat(Qt.PlainText)
        self.setWordWrap(True)
        self.hide()

    def setText(self, value):
        super().setText(value)
        self.setVisible(bool(value))


